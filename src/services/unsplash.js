const UNSPLASH_KEY = import.meta.env.VITE_UNSPLASH_ACCESS_KEY || FALLBACK_UNSPLASH_KEY;

// Global Persistent Registry of Used Unsplash IDs & URLs
const USED_IMAGES_KEY = 'lumaa_used_unsplash_ids';

export function getUsedImageIds() {
  try {
    const stored = localStorage.getItem(USED_IMAGES_KEY);
    return stored ? JSON.parse(stored) : [];
  } catch (e) {
    return [];
  }
}

export function registerUsedImageId(id) {
  if (!id) return;
  try {
    const existing = getUsedImageIds();
    if (!existing.includes(id)) {
      const updated = [...existing, id];
      localStorage.setItem(USED_IMAGES_KEY, JSON.stringify(updated));
    }
  } catch (e) {
    console.error('Error saving used image id:', e);
  }
}

/**
 * Clean and sanitize alt text string
 */
function sanitizeAlt(text) {
  if (!text || typeof text !== 'string') return 'Luxury British Interior';
  return text.replace(/&/g, 'and').trim();
}

/**
 * Fetches a guaranteed unique, high-definition luxury UK interior/architecture image from Unsplash.
 * Uses specific targeted search queries generated by Gemini, with multi-level fallbacks and zero duplicates.
 * 
 * @param {string|string[]} searchQueries - Specific search query or array of targeted queries from Gemini
 * @param {string} category - Category name (e.g., 'Kitchen', 'Living Room')
 * @param {string} customAlt - Custom SEO-optimized alt text generated by Gemini
 */
export async function fetchUniqueUnsplashImage(searchQueries = [], category = 'Living Room', customAlt = '') {
  const usedIds = getUsedImageIds();
  
  // Normalize queries array
  const queries = Array.isArray(searchQueries) 
    ? searchQueries.filter(q => Boolean(q && q.trim()))
    : [searchQueries].filter(q => Boolean(q && q.trim()));

  // Add category-based backup queries
  queries.push(
    `luxury ${category} interior architecture`,
    `british ${category} design high end`,
    `english country home ${category} decor`
  );

  for (const query of queries) {
    try {
      const encoded = encodeURIComponent(query.trim());
      // Random page between 1 and 3 for diverse fresh results
      const page = Math.floor(Math.random() * 2) + 1;
      const url = `https://api.unsplash.com/search/photos?query=${encoded}&orientation=landscape&per_page=25&page=${page}&client_id=${UNSPLASH_KEY}`;

      const res = await fetch(url);
      if (!res.ok) continue;

      const data = await res.json();
      if (data.results && data.results.length > 0) {
        // Find the first photo not yet registered in used IDs
        const freshPhoto = data.results.find(p => !usedIds.includes(p.id));

        if (freshPhoto) {
          registerUsedImageId(freshPhoto.id);
          return {
            id: freshPhoto.id,
            url: freshPhoto.urls.regular || freshPhoto.urls.full,
            alt: sanitizeAlt(customAlt || freshPhoto.alt_description || query),
            photographer: freshPhoto.user?.name || 'Unsplash Contributor',
            photographerUrl: freshPhoto.user?.links?.html || 'https://unsplash.com'
          };
        }
      }
    } catch (err) {
      console.warn('Unsplash query attempt error:', err);
    }
  }

  // Deep Fallback: Fetch latest curated editorial photos
  return getCuratedOrRandomFallback(category, customAlt);
}

